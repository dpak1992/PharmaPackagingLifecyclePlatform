class TestTextCompare:
    def test_exact_match_high_ratio(self):
        """When artwork text matches approved text, ratio should be high."""
        config = _make_config()
        artwork = _make_complete_artwork(config)
        # Use the artwork's own text as approved
        approved = " ".join(el.content for el in artwork.text_elements)
        results = compare_text(artwork, approved)

        ratio_result = next(r for r in results if r.check_id == "TEXT-001")
        assert ratio_result.status == CheckStatus.PASS

    def test_missing_text_flagged(self):
        """Missing text from approved source must be flagged."""
        config = _make_config()
        artwork = _make_complete_artwork(config)
        # Approved text has extra content not in artwork
        approved = (
            " ".join(el.content for el in artwork.text_elements)
            + " ADDITIONAL MANDATORY REGULATORY TEXT REQUIRED"
        )
        results = compare_text(artwork, approved)

        missing_result = next(r for r in results if r.check_id == "TEXT-002")
        assert missing_result.status == CheckStatus.FAIL
        assert "ADDITIONAL" in missing_result.details

    def test_extra_text_flagged(self):
        """Extra text in artwork not in approved source gets a warning."""
        config = _make_config()
        artwork = _make_complete_artwork(config)
        # Use only part of the artwork text as approved
        approved = artwork.text_elements[0].content
        results = compare_text(artwork, approved)

        extra_result = next(r for r in results if r.check_id == "TEXT-003")
        assert extra_result.status == CheckStatus.WARNING


