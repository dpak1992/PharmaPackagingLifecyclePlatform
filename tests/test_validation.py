class TestRevisionCompare:
    def test_no_changes_detected(self):
        """Identical artwork versions should report no changes."""
        config = _make_config()
        artwork = _make_complete_artwork(config)
        results = compare_revisions(artwork, artwork)

        assert len(results) == 1
        assert results[0].check_id == "REV-000"
        assert results[0].status == CheckStatus.PASS

    def test_added_element_detected(self):
        """Adding a text element should be detected."""
        config = _make_config()
        old_art = _make_complete_artwork(config)
        new_art = _make_complete_artwork(config)
        new_art.text_elements.append(TextElement(
            id="new-element",
            content="New regulatory text",
            source_field="static",
            panel_type=PanelType.BACK,
            x=5.0, y=120.0,
        ))
        results = compare_revisions(old_art, new_art)

        added = [r for r in results if r.check_id == "REV-001"]
        assert len(added) == 1
        assert "new-element" in added[0].element

    def test_removed_element_detected(self):
        """Removing a text element should be detected."""
        config = _make_config()
        old_art = _make_complete_artwork(config)
        new_art = _make_complete_artwork(config)
        new_art.text_elements = new_art.text_elements[1:]  # Remove first
        results = compare_revisions(old_art, new_art)

        removed = [r for r in results if r.check_id == "REV-002"]
        assert len(removed) == 1

    def test_modified_content_detected(self):
        """Modifying text content should be detected."""
        config = _make_config()
        old_art = _make_complete_artwork(config)
        new_art = _make_complete_artwork(config)
        new_art.text_elements[0].content = "CHANGED BRAND NAME"
        results = compare_revisions(old_art, new_art)

        modified = [r for r in results if r.check_id == "REV-003"]
        assert len(modified) == 1
        assert "CHANGED BRAND NAME" in modified[0].details

    def test_color_change_detected(self):
        """Adding or removing a spot color should be detected."""
        config = _make_config()
        old_art = _make_complete_artwork(config)
        new_art = _make_complete_artwork(config)
        new_art.spot_colors.append(SpotColor(
            name="Pantone 185 C",
            cyan=0, magenta=100, yellow=80, black=0,
        ))
        results = compare_revisions(old_art, new_art)

        color_results = [r for r in results if r.check_id == "REV-010"]
        assert len(color_results) == 1
        assert "Pantone 185 C" in color_results[0].element


