class TestBarcodeValidate:
    def test_valid_ean13_passes(self):
        """A valid EAN-13 barcode with correct check digit passes."""
        artwork = ArtworkSpec(
            id="ART-TEST",
            barcodes=[BarcodeElement(
                id="ean13",
                barcode_type=BarcodeType.EAN_13,
                data="4006381333931",  # valid EAN-13
                panel_type=PanelType.BACK,
                x=5.0, y=45.0,
                width=37.29,
                height=25.93,
            )],
        )
        results = validate_barcodes(artwork)

        # All checks should pass
        failures = [r for r in results if r.status == CheckStatus.FAIL]
        assert len(failures) == 0, (
            f"Unexpected failures: "
            f"{[(r.check_id, r.message) for r in failures]}"
        )

    def test_invalid_check_digit_caught(self):
        """EAN-13 with wrong check digit must be flagged."""
        artwork = ArtworkSpec(
            id="ART-TEST",
            barcodes=[BarcodeElement(
                id="ean13-bad",
                barcode_type=BarcodeType.EAN_13,
                data="4006381333932",  # last digit wrong
                panel_type=PanelType.BACK,
                x=5.0, y=45.0,
                width=37.29,
                height=25.93,
            )],
        )
        results = validate_barcodes(artwork)

        check_digit_fail = next(
            r for r in results if r.check_id == "BAR-002"
        )
        assert check_digit_fail.status == CheckStatus.FAIL
        assert check_digit_fail.severity == Severity.CRITICAL

    def test_undersized_barcode_caught(self):
        """Barcode below GS1 minimum dimensions must be flagged."""
        artwork = ArtworkSpec(
            id="ART-TEST",
            barcodes=[BarcodeElement(
                id="ean13-small",
                barcode_type=BarcodeType.EAN_13,
                data="4006381333931",
                panel_type=PanelType.BACK,
                x=5.0, y=45.0,
                width=20.0,   # below 29.83mm minimum
                height=15.0,  # below 22.85mm minimum
            )],
        )
        results = validate_barcodes(artwork)

        width_fail = next(r for r in results if r.check_id == "BAR-003")
        assert width_fail.status == CheckStatus.FAIL

        height_fail = next(r for r in results if r.check_id == "BAR-004")
        assert height_fail.status == CheckStatus.FAIL

    def test_non_digit_data_caught(self):
        """EAN-13 with non-digit data must be flagged."""
        artwork = ArtworkSpec(
            id="ART-TEST",
            barcodes=[BarcodeElement(
                id="ean13-alpha",
                barcode_type=BarcodeType.EAN_13,
                data="40063813ABC31",
                panel_type=PanelType.BACK,
                x=5.0, y=45.0,
                width=37.29,
                height=25.93,
            )],
        )
        results = validate_barcodes(artwork)

        data_fail = next(r for r in results if r.check_id == "BAR-001")
        assert data_fail.status == CheckStatus.FAIL
        assert data_fail.severity == Severity.CRITICAL
