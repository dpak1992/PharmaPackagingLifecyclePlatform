def _make_product(**overrides) -> Product:
    defaults = dict(
        id="TEST-500",
        brand_name="AZICURE",
        generic_name="Azithromycin",
        strength=Strength(value=500, unit="mg"),
        dosage_form=DosageForm.TABLET,
        composition="Each tablet contains: Azithromycin IP 500 mg",
        manufacturer=Manufacturer(
            name="TestPharma Ltd.",
            address="123 Pharma Road, Mumbai",
            license_no="MH/15/123/2024",
        ),
    )
    defaults.update(overrides)
    return Product(**defaults)


def _make_config(mrp: str = None) -> PackagingConfig:
    product = _make_product()
    blister = BlisterSpec(length=120, width=50, height=8)
    config = PackagingConfig(
        product=product, blister=blister, pack_size="1 x 10", mrp=mrp
    )
    config.carton.calculate_from_blister(blister)
    return config


def _make_complete_artwork(config: PackagingConfig) -> ArtworkSpec:
    """Generate a complete artwork that should pass all checks."""
    return generate_default_artwork(config)


